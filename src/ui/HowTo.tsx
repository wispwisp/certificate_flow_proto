export default function HowTo({ onBack }: { onBack: () => void }) {
  return (
    <main className="howto">
      <button className="link" onClick={onBack}>← Назад</button>
      <h1>Как подготовить шаблон</h1>
      <p>Шаблон — обычный документ Word (.docx) с вашим фирменным бланком. Там, где должно стоять меняющееся значение, впишите метку в двойных фигурных скобках.</p>

      <h2>Как написать метку</h2>
      <p>Название поля в двойных фигурных скобках, например <code>{'{{ student_full_name }}'}</code> или <code>{'{{ birth_date }}'}</code>. Пробелы внутри скобок не мешают. Название пишется латинскими буквами, цифрами и знаком подчёркивания, без пробелов.</p>

      <h2>Какие названия допустимы</h2>
      <p>Начинайте название с буквы или подчёркивания. Для известных названий (<code>cert_number</code>, <code>student_full_name</code>, <code>group_name</code> и других) программа сама подставит понятную подпись. Для остальных подписью будет само название.</p>

      <h2>Таблица CSV</h2>
      <p>Если вы заполняете документы списком, название столбца в CSV должно совпадать с названием поля: столбец <code>group_name</code> попадёт в метку <code>{'{{ group_name }}'}</code>. Регистр букв не важен. Столбцы с другими названиями можно связать с полями вручную. Сохраните таблицу в формате CSV: Файл → Сохранить как → CSV UTF-8.</p>

      <h2>Даты</h2>
      <p>Если название поля заканчивается на <code>_date</code> (например <code>birth_date</code>), значение считается датой. Принимаются форматы ДД.ММ.ГГГГ, Д.М.ГГГГ и ГГГГ-ММ-ДД; в документе дата будет в виде ДД.ММ.ГГГГ.</p>

      <h2>Где можно ставить метки</h2>
      <p>В обычном тексте, в таблицах, в верхнем и нижнем колонтитулах.</p>

      <h2>Оформление</h2>
      <p>Значение берёт оформление метки: шрифт, размер, цвет и выравнивание. Выделите метку жирным — и значение будет жирным.</p>

      <h2>Что не поддерживается</h2>
      <p>Блоки вида <code>{'{% … %}'}</code> (условия и повторы) в демо-версии не обрабатываются.</p>

      <h2>Как сохранить файл</h2>
      <p>Сохраните шаблон в формате .docx: Файл → Сохранить как → Документ Word. Старый формат .doc не подходит.</p>

      <h2>Если Word «разбил» метку</h2>
      <p>Иногда Word внутри файла делит метку на части (например, из-за проверки орфографии). Это нормально: программа соберёт метку обратно.</p>
    </main>
  )
}
